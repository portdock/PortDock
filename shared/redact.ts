// 오류 보고에서 사용자를 알아볼 글을 가린다 — 화면 의존 없는 순수 함수(node --test 로 시험)

/**
 * «C:\Users\홍길동\…» → «~\…» — 윈도우 사용자 이름을 보고서에 남기지 않는다(JSON 의 «\\»·«/» 도).
 * 이름에 빈칸이 있어도(«John Smith») 다음 경로 구분자까지 가린다. 구분자가 없으면 빈칸 앞까지.
 */
export function hideUserPaths(text: string) {
  return text.replace(/\b[a-z]:(?:\\|\/)+users(?:\\|\/)+(?:[^\\/"'`<>|\r\n:]{1,64}?(?=\\|\/)|[^\\/\s"'`<>|]+)/gi, "~");
}
