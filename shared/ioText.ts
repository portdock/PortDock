export const IO = { ko, en };
export type IoKey = keyof typeof ko;

export function io(lang: Lang, k: IoKey, v: Record<string, string | number> = {}) {
  return IO[lang][k].replace(/\{(\w+)\}/g, (m, key: string) => (key in v ? String(v[key]) : m));
}
