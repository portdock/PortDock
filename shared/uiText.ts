export const UI = { ko, en };
export type UiKey = keyof typeof ko;

/** 공용 문구 + {a}·{n} 채우기 */
export function ui(lang: Lang, k: UiKey, v: Record<string, string | number> = {}) {
  return UI[lang][k].replace(/\{(\w+)\}/g, (m, key: string) => (key in v ? String(v[key]) : m));
}
