export type ArKey = keyof typeof ko;
export const AR_TEXT = { ko, en };

/** 문구 + {a}·{n} 채우기 */
export function ar(lang: Lang, k: ArKey, v: Record<string, string | number> = {}) {
  return AR_TEXT[lang][k].replace(/\{(\w+)\}/g, (m, key: string) => (key in v ? String(v[key]) : m));
}

