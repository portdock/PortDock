export type TFn = (k: Key, v?: Record<string, string | number>) => string;

/** «{n}개» 처럼 자리 채우기 */
export function fill(text: string, v: Record<string, string | number> = {}) {
  return text.replace(/\{(\w+)\}/g, (_, k) => (k in v ? String(v[k]) : `{${k}}`));
}
