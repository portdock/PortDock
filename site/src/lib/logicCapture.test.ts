// 로직 분석기 캡처 읽기 — Saleae CSV·sigrok CSV·VCD 를 조각으로 나눠 넣어도 같은 결과인지
import { test } from "node:test";
import assert from "node:assert/strict";
import { createParser, parseCapture, parseRate, valueAt, valueBefore, CaptureError } from "./logicCapture.ts";
import { Wave, toSaleaeCsv, toSigrokCsv, toVcd } from "./logicSynth.ts";

const near = (a: number, b: number, eps = 1e-12) => assert.ok(Math.abs(a - b) <= eps, `${a} ≠ ${b}`);

test("Saleae CSV: 머리 Time [s], 바뀔 때만 한 줄", () => {
  const c = parseCapture("Time [s],Channel 0,Channel 1\n0.000000000,1,0\n0.000010000,0,0\n0.000020000,1,1\n0.000030000,1,1\n");
  assert.equal(c.format, "saleae-csv");
  assert.deepEqual(
    c.channels.map((x) => x.name),
    ["Channel 0", "Channel 1"],
  );
  assert.equal(c.channels[0].init, 1);
  assert.deepEqual([...c.channels[0].t], [0.00001, 0.00002]);
  assert.deepEqual([...c.channels[1].t], [0.00002]);
  near(c.start, 0);
  near(c.end, 0.00003);
  assert.equal(valueAt(c.channels[0], 0.00001), 0);
  assert.equal(valueBefore(c.channels[0], 0.00001), 1);
});

test("sigrok CSV: 주석의 Samplerate, 시간 열 없음 → 샘플 번호 ÷ 속도", () => {
  const c = parseCapture("; CSV generated by libsigrok\n; Samplerate: 1 MHz\nD0,D1\n1,0\n1,0\n0,0\n0,1\n");
  assert.equal(c.format, "sigrok-csv");
  assert.equal(c.rate, 1e6);
  near(c.channels[0].t[0], 2e-6);
  near(c.channels[1].t[0], 3e-6);
  near(c.end, 4e-6);
  assert.deepEqual(c.warnings, []);
});

test("시간 열 없는 CSV 에 속도 정보가 없으면 사용자 값 + 알림", () => {
  const c = parseCapture("A,B\n0,1\n1,1\n", { sampleRate: 4e6 });
  assert.equal(c.rate, 4e6);
  near(c.channels[0].t[0], 0.25e-6);
  assert.ok(c.warnings.includes("rate-assumed"));
});

test("시간 열 단위(ms)·아날로그 열 문턱", () => {
  const c = parseCapture("Time (ms),V\n0,0.1\n1,3.2\n2,0.2\n", { threshold: 1.5 });
  assert.deepEqual([...c.channels[0].t], [0.001, 0.002]);
  assert.ok(c.warnings.includes("analog"));
});

test("시간이 거꾸로 가면 오류", () => {
  assert.throws(() => parseCapture("Time [s],A\n0.2,0\n0.1,1\n"), (e: unknown) => e instanceof CaptureError && e.code === "unsorted");
});

test("VCD: timescale, $dumpvars, x·z, 벡터 펼치기", () => {
  const v = ["$timescale 10ns $end", "$scope module m $end", "$var wire 1 ! clk $end", "$var wire 2 # bus [1:0] $end", "$upscope $end", "$enddefinitions $end", "#0", "$dumpvars", "0!", "b01 #", "$end", "#5", "1!", "#7", "z!", "#9", "b10 #", "#12", "x!", "#20"].join("\n");
  const c = parseCapture(v);
  assert.equal(c.format, "vcd");
  assert.deepEqual(
    c.channels.map((x) => x.name),
    ["clk", "bus[1]", "bus[0]"],
  );
  near(c.channels[0].t[0], 50e-9, 1e-15); // 1! at #5
  assert.equal(c.channels[0].t.length, 1); // z → 1 그대로, x → 앞 값
  assert.deepEqual([...c.channels[1].t].map((x) => Math.round(x * 1e9)), [90]);
  assert.deepEqual([...c.channels[2].t].map((x) => Math.round(x * 1e9)), [90]);
  near(c.end, 200e-9, 1e-15);
  assert.ok(c.warnings.includes("x-values"));
});

test("조각으로 나눠 넣어도 같다(줄·토큰 가운데에서 잘림)", () => {
  const a = new Wave(1);
  const b = new Wave(0);
  for (let k = 1; k < 200; k++) (k % 3 ? a : b).set(k * 1e-6, (k % 2) as 0 | 1);
  const chs = [
    { name: "A", sig: a.sig() },
    { name: "B", sig: b.sig() },
  ];
  for (const text of [toSaleaeCsv(chs, 0, 2e-4), toVcd(chs, 0, 2e-4), toSigrokCsv(chs, 1e6, 210)]) {
    const whole = parseCapture(text);
    for (const step of [1, 7, 64, 1000]) {
      const p = createParser();
      for (let i = 0; i < text.length; i += step) p.push(text.slice(i, i + step));
      const part = p.finish();
      assert.deepEqual(
        part.channels.map((c) => [...c.t]),
        whole.channels.map((c) => [...c.t]),
      );
    }
    // 원래 파형과 같다
    whole.channels.forEach((c, i) => {
      assert.equal(c.init, chs[i].sig.init);
      assert.equal(c.t.length, chs[i].sig.t.length);
      c.t.forEach((x, k) => near(x, chs[i].sig.t[k], 1e-9));
    });
  }
});

test("BOM·빈 파일·속도 글", () => {
  assert.equal(parseCapture("﻿Time [s],A\n0,1\n1,0\n").channels[0].t.length, 1);
  assert.throws(() => parseCapture("  \n"), (e: unknown) => e instanceof CaptureError && e.code === "empty");
  assert.equal(parseRate("24 MHz"), 24e6);
  assert.equal(parseRate("500kHz"), 5e5);
  assert.equal(parseRate("fast"), null);
});

test("변화 수 상한", () => {
  const rows = ["Time [s],A"];
  for (let k = 0; k < 50; k++) rows.push(`${k},${k & 1}`);
  assert.throws(() => parseCapture(rows.join("\n"), { maxEdges: 10 }), (e: unknown) => e instanceof CaptureError && e.code === "too-many-edges");
});

test("파형 경로: 적으면 그대로, 많으면 화소마다 줄임", async () => {
  const { wavePath } = await import("./logicCapture.ts");
  const s = { init: 0 as const, t: Float64Array.from([1, 2, 3]) };
  assert.equal(wavePath(s, 0, 4, 40, 0, 10), "M0 10H10V0H20V10H30V0H40");
  const many = { init: 0 as const, t: Float64Array.from({ length: 1000 }, (_, i) => i / 1000) };
  const d = wavePath(many, 0, 1, 10, 0, 10);
  assert.ok(d.length < 400, d);
  assert.ok(d.endsWith("H10"));
});
